// Element catalog for the Scene Planner. Sizes are shares of the grid, so a
// waterfall covers the same part of the picture on a 5×5 and a 20×20 grid.

export type Zone = "sky" | "far" | "mid" | "front";

export type Shape = "point" | "block" | "column" | "band" | "path";

export type Theme =
  | "sky"
  | "nature"
  | "fields"
  | "wildlife"
  | "water"
  | "coast"
  | "village"
  | "urban";

export type TimeOfDay = "dawn" | "midday" | "golden" | "dusk" | "night";

export interface SceneElement {
  id: string;
  label: string;
  icon: string;
  theme: Theme;
  /** Zones the element's bottom row may sit in. Paths start in these zones. */
  zones: Zone[];
  shape: Shape;
  /** [min, max] share of the grid's columns. Paths use it for thickness. */
  width: [number, number];
  /** [min, max] share of the grid's rows. Paths use it for length. */
  height: [number, number];
  color: string;
  weight: number;
  max: number;
  /** Path element that starts under this element, such as a waterfall's stream. */
  feeds?: string;
  /** Paths get one cell wider in the front zone, for perspective. */
  widens?: boolean;
  /** Keeps width and height equal, for round things like the sun. */
  square?: boolean;
  /** Sits on top of these elements instead of on free cells, like ducks on a
   * pond. Riders ignore zones; their host decides where they can go. */
  on?: string[];
  /** Label and icon that replace the defaults at certain times of day. */
  variants?: Partial<Record<TimeOfDay, { label: string; icon: string }>>;
}

